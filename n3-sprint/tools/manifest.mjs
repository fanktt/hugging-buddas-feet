#!/usr/bin/env node
// Writes dist/manifest.js: the small index the app loads at start instead of the whole bank.
//   node tools/manifest.mjs           regenerate after adding or changing data files
// It lists, per data file, the ids/types/passage groups of its questions, its note ids and
// kinds, and the matching furigana file. validate.mjs fails when the file is out of date.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import zlib from 'node:zlib';
import {fileURLToPath} from 'node:url';
import {load, dist, legacyFiles} from './load.mjs';

export const manifestPath = path.join(dist, 'manifest.js');
const NOTE_KINDS = ['grammar', 'confuse'];
const pad = n => String(n).padStart(2, '0');

// Run-length items understood by Bank.manifest (see bank.js).
function encode(list, key, problems, file) {
  const runs = [];
  let i = 0;
  while (i < list.length) {
    const head = list[i];
    let run = runs[runs.length - 1];
    if (!run || run[0] !== head[key]) runs.push(run = [head[key]]);
    const same = (q, k) => q && q[key] === head[key];
    let k = 1;
    if (head.passageId && head.id === head.passageId + '-1') {
      while (same(list[i + k]) && list[i + k].passageId === head.passageId && list[i + k].id === head.passageId + '-' + (k + 1)) k++;
      run.push('@' + head.passageId + (k > 1 ? '*' + k : ''));
    } else {
      const m = /^(.+)-(\d+)$/.exec(head.id);
      if (!head.passageId && m && head.id === m[1] + '-' + pad(1)) {
        const base = m[1];
        while (same(list[i + k]) && !list[i + k].passageId && list[i + k].id === base + '-' + pad(k + 1)) k++;
        run.push(base + '*' + k);
      } else {
        if (/[*@]/.test(head.id)) problems.push(`${file} ${head.id}: ids must not contain * or @`);
        run.push(head.id);
      }
    }
    i += k;
  }
  return runs;
}

// Returns {text, problems, files}. `files` is what the manifest describes, in app order.
export function build() {
  const {bank, fileOf, failures, files} = load();
  const problems = [...failures];
  const typeOrder = Object.keys(bank.TYPES);
  const byFile = new Map(files.map(f => [f, {questions: [], notes: []}]));
  for (const q of bank.questions) byFile.get(fileOf.get(q))?.questions.push(q);
  for (const n of bank.notes) byFile.get(fileOf.get(n))?.notes.push(n);
  // Legacy files first, then subjects in TYPES order, then notes; ties by name.
  const rank = f => {
    if (legacyFiles.includes(f)) return legacyFiles.indexOf(f) - 100;
    const {questions, notes} = byFile.get(f);
    if (questions.length) return Math.min(...questions.map(q => typeOrder.indexOf(q.type)));
    if (notes.length) return 1000 + Math.min(...notes.map(n => NOTE_KINDS.indexOf(n.kind)));
    return 2000;
  };
  const ordered = [...files].sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
  const rows = [];
  for (const file of ordered) {
    const {questions, notes} = byFile.get(file);
    for (const q of questions) {
      if (bank.TYPES[q.type] && bank.TYPES[q.type].cat !== q.cat) problems.push(`${file} ${q.id}: cat ${q.cat} does not match type ${q.type}`);
    }
    const ruby = 'ruby/' + path.basename(file);
    const rubyFile = fs.existsSync(path.join(dist, ruby)) ? ruby : '';
    rows.push([file, rubyFile, encode(questions, 'type', problems, file), encode(notes, 'kind', problems, file)]);
  }
  const text = '// Generated by tools/manifest.mjs. Do not edit: run `node tools/manifest.mjs` after changing the bank.\n' +
    '// Per data file: [file, furigana file, [[type, ...ids]], [[note kind, ...ids]]]; id runs are explained in bank.js.\n' +
    'Bank.manifest([\n' + rows.map(r => JSON.stringify(r)).join(',\n') + '\n]);\n';

  // Round trip: what the app will rebuild from the text must equal the bank.
  const context = vm.createContext({});
  vm.runInContext(fs.readFileSync(path.join(dist, 'bank.js'), 'utf8'), context);
  vm.runInContext(text, context);
  const cat = context.Bank.catalog;
  const fileRank = new Map(ordered.map((f, i) => [f, i]));
  const expectQ = [...bank.questions].sort((a, b) => fileRank.get(fileOf.get(a)) - fileRank.get(fileOf.get(b)));
  const expectN = [...bank.notes].sort((a, b) => fileRank.get(fileOf.get(a)) - fileRank.get(fileOf.get(b)));
  const qKey = q => [q.id, q.type, q.passageId || ''].join('|');
  const sameQ = cat.questions.length === expectQ.length && cat.questions.every((q, i) => qKey(q) === qKey(expectQ[i]) && q.file === fileOf.get(expectQ[i]));
  const sameN = cat.notes.length === expectN.length && cat.notes.every((n, i) => n.id === expectN[i].id && n.kind === expectN[i].kind && n.file === fileOf.get(expectN[i]));
  if (!sameQ || !sameN) problems.push('manifest round trip does not reproduce the bank (duplicate ids or an unsupported id pattern?)');
  return {text, problems, files: ordered};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const {text, problems, files} = build();
  for (const p of problems) console.log('ERROR ' + p);
  if (problems.length) process.exit(1);
  const before = fs.existsSync(manifestPath) ? fs.readFileSync(manifestPath, 'utf8') : '';
  if (before !== text) fs.writeFileSync(manifestPath, text);
  console.log(`${before === text ? 'unchanged' : 'wrote'} dist/manifest.js: ${files.length} files, ` +
    `${text.length} bytes, ${zlib.gzipSync(text).length} bytes gzipped`);
}
